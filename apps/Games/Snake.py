def rotate_90(tile):
    N = SPRITE_SIZE
    result = bytearray(N * N * 2)
    for row in range(N):
        for col in range(N):
            src = ((N - 1 - col) * N + row) * 2
            dst = (row * N + col) * 2
            result[dst]     = tile[src]
            result[dst + 1] = tile[src + 1]
    return bytes(result)

def _make_rotations(base):
    r0 = base
    r1 = rotate_90(r0)
    r2 = rotate_90(r1)
    r3 = rotate_90(r2)
    return (r0, r1, r2, r3)

